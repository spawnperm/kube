export function generateQuizForKnowledge(options: {
  topic?: string;
  articleSlug?: string;
  grade?: string;
  count?: number;
}): QuizQuestionItem[] {
  const { topic, articleSlug, count = 5 } = options;
  let pool = [...KNOWLEDGE_QUIZ_BANK];

  if (articleSlug) {
    const matched = pool.filter((q) => q.articleSlug === articleSlug);
    if (matched.length > 0) {
      pool = matched;
    }
  } else if (topic) {
    const lower = topic.toLowerCase();
    const matched = pool.filter(
      (q) =>
        q.topicTitle.toLowerCase().includes(lower) ||
        q.category.toLowerCase().includes(lower) ||
        q.question.toLowerCase().includes(lower),
    );
    if (matched.length > 0) {
      pool = matched;
    }
  }

  // Shuffle pool
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
