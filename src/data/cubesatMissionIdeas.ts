function getShortInstrument(name: string): string {
  if (name.includes('SAR') || name.includes('радар') || name.includes('Радар')) return 'SAR-радар';
  if (name.includes('гиперспектрометр') || name.includes('Гиперспектрометр'))
    return 'гиперспектрометр';
  if (name.includes('лидар') || name.includes('Лидар') || name.includes('высотомер'))
    return 'лазерный высотомер';
  if (name.includes('Мультиспектральная') || name.includes('мультиспектральный'))
    return 'мультиспектрометр';
  if (name.includes('Оптико-электронный') || name.includes('камера') || name.includes('Камера'))
    return 'оптический комплекс';
  if (name.includes('микрофлюидный') || name.includes('Lab-on-a-Chip')) return 'микрофлюидный чип';
  if (name.includes('Биореактор') || name.includes('биореактор')) return 'биореактор СЖО';
  if (name.includes('микроскоп')) return 'биомикроскоп';
  if (name.includes('кристаллизации')) return 'кассета кристаллизации';
  if (name.includes('Биомодуль') || name.includes('биомодуль')) return 'гермомодуль';
  if (name.includes('гамма-спектрометр')) return 'гамма-спектрометр';
  if (name.includes('поляриметр') || name.includes('дрейфовый')) return 'рентгеновский детектор';
  if (name.includes('фотометр')) return 'УФ-фотометр';
  if (name.includes('магнитометр')) return 'квантовый магнитометр';
  if (name.includes('детектор суммарного потока')) return 'детектор частиц';
  if (name.includes('квантового распределения') || name.includes('QKD')) return 'QKD-терминал';
  if (name.includes('лазерный терминал')) return 'лазерный терминал';
  if (name.includes('SDR')) return 'SDR-трансивер';
  if (name.includes('Фазированная') || name.includes('антенная')) return 'ФАР Ka-диапазона';
  if (name.includes('ретранслятор') || name.includes('радиомаяк')) return 'цифровой ретранслятор';
  if (name.includes('тросовая') || name.includes('трос')) return 'электродинамический трос';
  if (name.includes('двигатель') || name.includes('Двигатель')) return 'микродвигатель';
  if (name.includes('солнечного паруса')) return 'солнечный парус';
  if (name.includes('звездный датчик') || name.includes('Звездный датчик'))
    return 'звездный датчик';
  if (name.includes('маховиков')) return 'маховики ориентации';
  if (name.includes('пеленгатор')) return 'пеленгатор РЭР';
  if (name.includes('радиометр MWIR') || name.includes('MWIR')) return 'MWIR-радиометр';
  if (name.includes('стереокамерой') || name.includes('инспекции')) return 'комплекс инспекции';
  if (name.includes('защиты')) return 'модуль радиозащиты';
  if (name.includes('метанового') || name.includes('метана')) return 'спектрометр метана';
  if (name.includes('флуоресценции') || name.includes('SIF')) return 'SIF-спектрометр';
  if (name.includes('нефелометр')) return 'поляризационный нефелометр';
  if (name.includes('микроволновый') || name.includes('радиометр'))
    return 'микроволновый радиометр';
  if (name.includes('тепловизор') || name.includes('ИК-сканер')) return 'тепловизор';
  if (name.includes('памяти')) return 'радиационно-стойкая память';
  if (name.includes('культурного наследия')) return 'мониторинг наследия';
  if (name.includes('популяризации')) return 'комплекс радиовещания';
  if (name.includes('многоязычных') || name.includes('APRS')) return 'модуль APRS/SSTV';
  if (name.includes('ЦМР') || name.includes('стереоскопический')) return 'стереомодуль ЦМР';
  if (name.includes('радиозатменный') || name.includes('GNSS')) return 'радиозатменный комплекс';
  if (name.includes('спрайтов')) return 'высокоскоростной фотометр';
  if (name.includes('стандарт частоты') || name.includes('CSAC')) return 'квантовый стандарт CSAC';
  if (name.includes('ГНСС-приемник') || name.includes('CRPA')) return 'CRPA-приемник';
  if (name.includes('навигационный приемник')) return 'ГЛОНАСС/GPS приемник';
  return name.split(' ')[0];
}

